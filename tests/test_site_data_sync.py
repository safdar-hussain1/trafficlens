"""The site's baked figures must be exactly what ``reports/`` measured.

Every number the results sections print comes from
``web/src/generated/reports.ts``, which ``scripts/build_site_data.py`` bakes from
``reports/*.json`` and the model card. This module is what stops that artefact
drifting from its sources, and it is built against a failure this repository has
already met once: **byte equality between a generator and its own output is a
tautology.** An exporter that publishes only a subset of its inputs passes a
byte-equality check happily, because regenerating reproduces the same hole.

So there are four independent mechanisms here, not one:

1. byte equality with a fresh bake -- catches a hand-edited artefact and a report
   edited without re-baking, and both directions are asserted mechanically below
   rather than argued for in a comment;
2. a hand-written coverage table -- pointers into the reports that MUST be
   published, written here and not read from the generator, so a field silently
   dropped from the spec fails even though the artefact still round-trips;
3. a containment sweep -- every published scalar must be a value that actually
   occurs in its own source report, so a figure cannot be invented or mistyped;
4. the derived values, recomputed here from the source JSON with the formula
   written out again, so a bug in the generator's arithmetic does not become the
   page's arithmetic.

Plus the redaction: no absolute km/h derived from ``motorway-a40.webm`` may reach
the page. That clip has no independent along-road anchor, its along-road scale is
bracketed at -33 %/+0 %, and the engine returns ``None`` for speed on it by
design -- see ``reports/speed_real.json``. The guard is asserted over the baked
artefact, the authored HTML and the published ``docs/`` alike.
"""

import json
import math
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "scripts" / "build_site_data.py"
REPORTS_DIR = ROOT / "reports"
MODEL_CARD = ROOT / "web" / "public" / "models" / "MODEL_CARD.md"
TS_GENERATED = ROOT / "web" / "src" / "generated" / "reports.ts"

HEADER = "// generated by scripts/build_site_data.py — do not edit"

#: Floors, so no assertion in this module can pass by finding nothing. Two empty
#: structures compare equal, so without these an emptied spec would satisfy byte
#: equality, the containment sweep and the coverage table alike.
MINIMUM_PUBLISHED_SCALARS = 900
MINIMUM_SECTIONS = 8

#: The published figure this project must never restate. It is the maximum speed
#: the parity fixture recorded on the flagship clip, and it is in reports/ for the
#: cross-surface comparison's own purposes -- but the clip ships uncalibrated, so
#: as a published figure it would assert a scale the survey withdrew.
FORBIDDEN_SPEED_KEY = "maxSpeedKmh"


def _run(*args: str) -> subprocess.CompletedProcess:
    """Drive the generator the way a developer does: as a script."""
    return subprocess.run(
        [sys.executable, str(GENERATOR), *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )


def _bake(out_path: Path, reports: Path | None = None, card: Path | None = None):
    args = ["--out", str(out_path)]
    if reports is not None:
        args += ["--reports", str(reports)]
    if card is not None:
        args += ["--model-card", str(card)]
    return _run(*args)


def _bake_or_fail(out_path: Path) -> bytes:
    result = _bake(out_path)
    assert result.returncode == 0, (
        f"the generator failed on the committed reports:\n"
        f"{result.stdout}\n{result.stderr}"
    )
    return out_path.read_bytes()


def _published() -> dict:
    """The committed artefact's data, parsed out of the TypeScript.

    The file is one `export const REPORTS = <json> as const;` declaration, so the
    payload is sliced out and parsed as JSON rather than the TypeScript being
    executed -- the test must not depend on a JavaScript runtime.
    """
    text = TS_GENERATED.read_text(encoding="utf-8")
    marker = "export const REPORTS = "
    start = text.index(marker) + len(marker)
    end = text.rindex(" as const;")
    return json.loads(text[start:end])


def _source(name: str) -> dict:
    return json.loads((REPORTS_DIR / name).read_text(encoding="utf-8"))


def _resolve(document, pointer: str):
    """The value at a ``/``-separated pointer. The test's own resolver, so a bug
    in the generator's cannot hide behind itself."""
    here = document
    for step in pointer.split("/"):
        if isinstance(here, list):
            here = here[int(step)]
        else:
            here = here[step]
    return here


def _scalars(value, out: list | None = None) -> list:
    """Every scalar in a nested structure, in traversal order."""
    out = [] if out is None else out
    if isinstance(value, dict):
        for item in value.values():
            _scalars(item, out)
    elif isinstance(value, list):
        for item in value:
            _scalars(item, out)
    else:
        out.append(value)
    return out


# --- The load-bearing byte comparison, and both of its directions -------------


def test_generated_reports_are_byte_identical_to_a_fresh_bake(tmp_path):
    fresh = _bake_or_fail(tmp_path / "reports.ts")
    committed = TS_GENERATED.read_bytes()
    assert fresh == committed, (
        f"{TS_GENERATED.relative_to(ROOT)} is out of sync with reports/. Never "
        f"edit it by hand -- run:\n"
        f"    PYTHONPATH=src .venv/bin/python scripts/build_site_data.py"
    )


def test_editing_a_report_moves_the_bake(tmp_path):
    """Direction one, mechanically: a changed measurement changes the artefact.

    Without this the byte comparison above could be passing over a generator that
    ignores its inputs -- and a generator that ignored its inputs would keep
    passing it forever.
    """
    reports = tmp_path / "reports"
    shutil.copytree(REPORTS_DIR, reports, ignore=shutil.ignore_patterns("figures"))
    document = json.loads((reports / "counting_accuracy.json").read_text())
    before = document["methods"]["engine+gate"]["full"]["f1"]
    document["methods"]["engine+gate"]["full"]["f1"] = before + 0.01
    (reports / "counting_accuracy.json").write_text(json.dumps(document))

    result = _bake(tmp_path / "moved.ts", reports=reports)
    assert result.returncode == 0, result.stderr
    assert (tmp_path / "moved.ts").read_bytes() != TS_GENERATED.read_bytes(), (
        "a changed F1 in the source report did not change the baked artefact, so "
        "the byte comparison is not actually watching the reports"
    )


def test_editing_the_artefact_breaks_the_comparison(tmp_path):
    """Direction two: a hand-edited artefact no longer matches a fresh bake."""
    tampered = TS_GENERATED.read_bytes().replace(b"0.9142857142857143", b"0.9999", 1)
    assert tampered != TS_GENERATED.read_bytes(), (
        "the engine's committed F1 is not in the artefact, so this control is "
        "not exercising anything"
    )
    assert tampered != _bake_or_fail(tmp_path / "reports.ts")


def test_the_bake_is_deterministic_across_runs(tmp_path):
    """Same inputs, same bytes -- otherwise `docs/` could not be reproduced."""
    assert _bake_or_fail(tmp_path / "first.ts") == _bake_or_fail(tmp_path / "second.ts")


def test_the_artefact_carries_the_do_not_edit_header():
    assert TS_GENERATED.read_text(encoding="utf-8").splitlines()[0] == HEADER


