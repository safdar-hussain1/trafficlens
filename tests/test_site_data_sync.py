@pytest.mark.parametrize(
    ("row", "column"),
    [
        ("File size", 1),
        ("File size", 2),
        ("Detections over 40 frames", 1),
        ("Detections over 40 frames", 2),
        ("Recall against float32", 2),
        ("Mean IoU of matched boxes", 2),
    ],
)
def test_a_model_card_cell_emptied_with_an_em_dash_refuses_the_bake(tmp_path, row, column):
    """EVERY declared cell, not only the ones the derived figures are computed from.

    This is the condition the model card was accepted as a second data source on:
    the parse fails loudly. It did not, for three of the five figures -- a card
    with an em-dashed ``Detections over 40 frames`` int8 cell exited 0 and baked
    ``model.detections.int8 = null``, and the architecture table then printed that
    null into a published comparison. A silent fallback here turns the ruling into
    a hole, so the refusal is asserted cell by cell.
    """
    text = MODEL_CARD.read_text(encoding="utf-8")
    for line in text.splitlines():
        if line.startswith(f"| {row} |"):
            parts = line.split("|")
            assert parts[column + 1].strip() not in {"", "—"}, (
                f"the {row!r} row already leaves column {column} empty, so this "
                f"mutation is not removing anything"
            )
            parts[column + 1] = " — "
            emptied = text.replace(line, "|".join(parts))
            break
    else:  # pragma: no cover - the row labels are asserted above
        pytest.fail(f"the card has no row labelled {row!r}")

    assert emptied != text, "the card was not modified, so nothing is being tested"
    card = tmp_path / "MODEL_CARD.md"
    card.write_text(emptied, encoding="utf-8")
    result = _bake(tmp_path / "out.ts", card=card)
    assert result.returncode != 0, result.stdout
    assert row in result.stderr


def test_the_committed_model_card_bakes_with_every_declared_cell_filled(tmp_path):
    """The control on the parametrised refusal above, varying a different axis:
    the same declared cells, unmodified. Without it, a generator that refused
    every card would satisfy all six mutations."""
    result = _bake(tmp_path / "out.ts")
    assert result.returncode == 0, result.stderr
    model = _published()["model"]
    for key in ("fileSizeBytes", "detections"):
        assert model[key]["float32"] is not None and model[key]["int8"] is not None
    for key in ("recallAgainstFloat32", "meanIouOfMatched"):
        assert model[key]["int8"] is not None


