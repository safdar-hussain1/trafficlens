def _baked_key_names() -> set:
    return {name for name in _method_names(_published()) if name != "source"}


def _rendering_text() -> str:
    return "".join((ROOT / path).read_text(encoding="utf-8") for path in RENDERING_SOURCES)


def test_no_baked_key_is_both_unread_and_unguarded():
    """Exact set equality, in both directions.

    A new baked key that nothing renders must be pinned here or removed -- it
    cannot simply appear. And a key that STARTS being rendered must come off this
    list, so the list cannot quietly accumulate keys that are now covered twice
    while a genuinely orphaned one hides among them.
    """
    text = _rendering_text()
    for path in RENDERING_SOURCES:
        assert (ROOT / path).exists(), f"{path} is missing; this guard must not pass by absence"
    unread = {
        name
        for name in _baked_key_names()
        if re.search(rf"\b{re.escape(name)}\b", text) is None
    }
    assert unread == {key for key, _baked, _source in UNRENDERED}, (
        "baked keys the page does not read changed. Add each new one to UNRENDERED "
        "with the report cell it comes from, or drop it from the spec; remove any "
        "that a section now renders."
    )


@pytest.mark.parametrize("entry", UNRENDERED, ids=lambda entry: entry[0])
def test_a_baked_key_the_page_does_not_read_still_matches_its_report(entry):
    key, baked_path, pointer = entry
    section = baked_path.split("/")[0]
    baked = _resolve(_published(), baked_path)
    source_value = _resolve(_source(SECTION_FILES[section]), pointer)
    assert type(baked) is type(source_value) and baked == source_value, (
        f"{baked_path} = {baked!r} but {SECTION_FILES[section]}:{pointer} = "
        f"{source_value!r}; key {key}"
    )


def _walk(value, path):
    if isinstance(value, dict):
        for key, item in value.items():
            yield from _walk(item, path + (key,))
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from _walk(item, path + (index,))
    else:
        yield path, value


def _method_names(document, out: set | None = None) -> set:
    """Every dict key in a report, so a key promoted into a row is recognised."""
    out = set() if out is None else out
    if isinstance(document, dict):
        for key, item in document.items():
            out.add(key)
            _method_names(item, out)
    elif isinstance(document, list):
        for item in document:
            _method_names(item, out)
    return out


# --- The redaction: no absolute km/h from the flagship clip -------------------


def test_the_flagship_clip_speed_is_in_the_reports_but_not_on_the_page():
    """A discriminating pair. The must-not-publish half is the rule; the
    must-still-exist half is what proves the guard is live -- if the field were
    simply gone from reports/, this test would be passing over nothing."""
    parity = _source("parity.json")
    assert FORBIDDEN_SPEED_KEY in parity["realClip"], (
        "the redacted field is no longer in reports/parity.json, so the guard "
        "below is passing over nothing; re-derive the redaction"
    )
    forbidden = parity["realClip"][FORBIDDEN_SPEED_KEY]

    artefact = TS_GENERATED.read_text(encoding="utf-8")
    assert FORBIDDEN_SPEED_KEY not in artefact
    assert repr(forbidden) not in artefact
    # Also the digits alone: a reformatted literal would slip past an exact
    # repr match, and it is the FIGURE that is prohibited, not its spelling.
    assert f"{forbidden:.2f}"[:6] not in artefact


