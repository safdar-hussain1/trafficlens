def test_every_report_file_is_published():
    """A benchmark that is not declared would never reach the site, and the
    artefact would regenerate byte-identically without it."""
    on_disk = {path.name for path in REPORTS_DIR.glob("*.json")}
    published = {
        section["source"].removeprefix("reports/")
        for key, section in _published().items()
        if key != "model"
    }
    assert published == on_disk, (
        "reports/ and the baked sections disagree; every report file must be "
        "declared in scripts/build_site_data.py"
    )


def test_the_artefact_is_not_vacuously_small():
    published = _published()
    assert len(published) >= MINIMUM_SECTIONS, sorted(published)
    scalars = _scalars(published)
    assert len(scalars) >= MINIMUM_PUBLISHED_SCALARS, (
        f"only {len(scalars)} published values; expected at least "
        f"{MINIMUM_PUBLISHED_SCALARS}. Two empty structures compare equal, so "
        f"without this floor an emptied spec passes every test here."
    )


