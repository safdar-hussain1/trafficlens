@pytest.mark.parametrize("entry", COVERAGE, ids=lambda entry: entry[0] + "|" + str(entry[-1]))
def test_every_load_bearing_figure_is_published_with_its_measured_value(entry):
    """A figure named here must be reachable in the artefact and equal to the
    source. This is the half that a subset cannot satisfy."""
    where, *pointer = entry
    section_key = where.split("/")[0]
    source_value = _resolve(_source(SECTION_FILES[section_key]), "/".join(str(p) for p in pointer))

    published = _resolve(_published(), where)
    found = _find_value(published, source_value)
    assert found, (
        f"{where} does not carry {source_value!r} from "
        f"{SECTION_FILES[section_key]}:{'/'.join(str(p) for p in pointer)}"
    )


def _find_value(haystack, needle) -> bool:
    """Whether ``needle`` occurs anywhere inside ``haystack``.

    The coverage table names the group a figure lands in rather than its exact
    baked key, because the baked shape is the generator's business and renaming a
    key must not be a test failure -- losing the measurement must be.
    """
    if isinstance(haystack, dict):
        return any(_find_value(item, needle) for item in haystack.values())
    if isinstance(haystack, list):
        if haystack == needle:
            return True
        return any(_find_value(item, needle) for item in haystack)
    if isinstance(haystack, float) and isinstance(needle, float):
        return haystack == needle
    return type(haystack) is type(needle) and haystack == needle


#: The values the bake computes rather than copies, with their formulae written
#: out a second time here. A derived figure is still a figure on the page.
def test_every_derived_value_recomputes_from_the_source_reports():
    published = _published()
    counting = _source("counting_accuracy.json")
    robustness = _source("robustness.json")

    labels = counting["labels"]["total"]
    engine = counting["methods"]["engine+gate"]["full"]

    def f1(tp, predicted, truth):
        return 2.0 * tp / (predicted + truth)

    expected_f1_step = abs(
        f1(engine["true_positives"], engine["n_predicted"], labels)
        - f1(engine["true_positives"], engine["n_predicted"] - 1, labels)
    )
    assert published["counting"]["resolution"]["oneEventF1"] == expected_f1_step
    assert published["counting"]["resolution"]["oneEventPrecision"] == 1.0 / labels

    expected_cpu = (
        counting["timing"]["engine+gate"]["ms_per_frame"]
        / counting["timing"]["centroid+gate"]["ms_per_frame"]
    )
    assert published["counting"]["engineCpuMultiple"] == expected_cpu

    stress = robustness["jitter_calibration"]["stress_multiple_at_max_sigma"]
    for end in ("lowest", "highest"):
        assert published["robustness"]["jitter"]["stressAtSigma2"][end] == (
            stress[end] * 2.0 / stress["sigma_px"]
        )

    card = MODEL_CARD.read_text(encoding="utf-8")
    sizes = [int(value.replace(" ", "")) for value in re.findall(r"\| (1?\d[\d ]{6,10}) B", card)]
    model = published["model"]
    assert model["bytesSaved"] == model["fileSizeBytes"]["float32"] - model["fileSizeBytes"]["int8"]
    assert model["fileSizeBytes"]["float32"] in sizes, sizes
    assert model["detectionsLostFraction"] == 1.0 - model["recallAgainstFloat32"]["int8"]


def test_every_published_number_occurs_in_its_own_source_report():
    """A figure cannot be invented, mistyped, or taken from the wrong report.

    The six derived values and each section's `source` string are the declared
    exceptions; everything else must be a value that literally appears in the
    report it claims to come from.
    """
    published = _published()
    derived = {
        ("counting", "resolution", "oneEventF1"),
        ("counting", "resolution", "oneEventPrecision"),
        ("counting", "engineCpuMultiple"),
        ("robustness", "jitter", "stressAtSigma2", "lowest"),
        ("robustness", "jitter", "stressAtSigma2", "highest"),
    }
    problems = []
    for key, file_name in SECTION_FILES.items():
        available = set()
        for value in _scalars(_source(file_name)):
            if isinstance(value, float) and not math.isfinite(value):
                continue
            available.add((type(value).__name__, value))
        for path, value in _walk(published[key], (key,)):
            if path in derived or path[-1] == "source":
                continue
            if isinstance(value, str) and value in {
                name for name in _method_names(_source(file_name))
            }:
                continue  # a dict key promoted into a row, e.g. "engine+gate"
            if (type(value).__name__, value) not in available:
                problems.append(f"{'/'.join(str(p) for p in path)} = {value!r}")
    assert problems == [], problems[:12]


# --- Baked keys nothing on the page reads -------------------------------------
#
# The one subset nothing else here can catch. `tsc --noEmit` cannot see an unused
# key, byte equality reproduces it happily, the containment sweep only says it came
# from the right report, and COVERAGE names figures a claim rests on -- which by
# definition these are not. So a key that nothing renders would be published,
# unread and unguarded, and a later task would find it and trust it.
#
# The rule adopted: no baked key may be referenced by nothing AND guarded by
# nothing. These are guarded here instead of trimmed, because trimming risks
# removing something a later task wants and pinning is the cheaper guarantee.
# Each entry pins the key's baked value to the report cell it came from, which is
# what COVERAGE does for the figures the page does print.

