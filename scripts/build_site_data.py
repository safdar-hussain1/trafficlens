Path_ = tuple[object, ...]


class SourceContractError(Exception):
    """A report, the model card, or the spec itself broke the contract."""


# -- the declaration vocabulary ------------------------------------------------
#
# Five field kinds and one derivation, and no more: anything that needs a sixth
# is a sign the page wants a shape the reports do not have.


class Value(NamedTuple):
    """One scalar, published under ``key``."""

    key: str
    path: Path_


class Series(NamedTuple):
    """A list of scalars, published verbatim and in source order."""

    key: str
    path: Path_


class Group(NamedTuple):
    """A nested object. Field paths are relative to ``path``."""

    key: str
    path: Path_
    fields: tuple


class Rows(NamedTuple):
    """A list of objects, each projected with ``fields``."""

    key: str
    path: Path_
    fields: tuple


class Keyed(NamedTuple):
    """A dict of objects, flattened to a list with the dict key kept.

    The reports key several tables by a name that is not a legal identifier --
    ``engine+gate``, ``box_jitter@sigma=2 px`` -- and an array of rows carrying
    that name in a field is both easier to render and stable under iteration
    order, which ``dict`` preserves from the file.
    """

    key: str
    path: Path_
    name: str
    fields: tuple


class Derived(NamedTuple):
    """A value computed from other measured values.

    ``inputs`` are resolved and handed to ``compute`` in order. ``why`` states
    the formula in words, because a derived number on a page about measurement
    has to say how it was arrived at.
    """

    key: str
    inputs: tuple[Path_, ...]
    compute: Callable[..., object]
    why: str


class Report(NamedTuple):
    """One source file and the section it produces."""

    key: str
    file: str
    fields: tuple


class Redaction(NamedTuple):
    """A path that exists in the source and must never reach the output."""

    file: str
    path: Path_
    reason: str


# -- resolution ----------------------------------------------------------------


def pointer(path: Path_) -> str:
    return "/".join(str(step) for step in path)


def resolve(document: object, path: Path_, origin: str) -> object:
    """The value at ``path``, or a refusal naming the pointer that broke.

    A missing path is never tolerated. The alternative -- emitting ``null`` and
    moving on -- is how a projection becomes a subset nobody notices: the
    artefact still regenerates byte-identically, so the sync test stays green
    while the page has quietly stopped showing a result.
    """
    here: object = document
    for index, step in enumerate(path):
        walked = pointer(path[: index + 1])
        if isinstance(step, int):
            if not isinstance(here, list):
                raise SourceContractError(
                    f"{origin}:{walked}: expected a list, found {type(here).__name__}"
                )
            if step >= len(here):
                raise SourceContractError(
                    f"{origin}:{walked}: index {step} is past the end "
                    f"({len(here)} items)"
                )
            here = here[step]
            continue
        if not isinstance(here, dict):
            raise SourceContractError(
                f"{origin}:{walked}: expected an object, found {type(here).__name__}"
            )
        if step not in here:
            raise SourceContractError(
                f"{origin}:{walked}: no such key (the report has "
                f"{sorted(here)[:8]}…)"
            )
        here = here[step]
    return here


def check_scalar(value: object, where: str) -> object:
    if value is None or isinstance(value, (bool, int, str)):
        return value
    if isinstance(value, float):
        if not math.isfinite(value):
            # json.dumps would emit `NaN` or `Infinity`, neither of which is a
            # TypeScript literal, so this would produce a file that does not
            # compile.
            raise SourceContractError(f"{where}: {value!r} is not finite")
        return value
    raise SourceContractError(
        f"{where}: {type(value).__name__} is not a scalar; declare it as a "
        f"Series, Rows or Group instead"
    )


def project(document: object, fields: tuple, origin: str, base: Path_ = ()) -> dict:
    """Apply ``fields`` to ``document``, returning a plain dict.

    Refuses duplicate keys. A collision would drop whichever field lost, and the
    hole would survive every regeneration, so byte equality could never see it --
    the same trap ``export_constants.py`` guards with its emitted-count check.
    """
    seen: list[str] = [field.key for field in fields]
    duplicates = sorted({key for key in seen if seen.count(key) > 1})
    if duplicates:
        raise SourceContractError(
            f"{origin}:{pointer(base) or '/'}: duplicate keys {duplicates}; one "
            f"of each pair would be dropped silently"
        )

    out: dict[str, object] = {}
    for field in fields:
        path = base + field.path if not isinstance(field, Derived) else base
        where = f"{origin}:{pointer(path) or '/'}"
        if isinstance(field, Value):
            out[field.key] = check_scalar(resolve(document, path, origin), where)
        elif isinstance(field, Series):
            found = resolve(document, path, origin)
            if not isinstance(found, list):
                raise SourceContractError(
                    f"{where}: Series needs a list, found {type(found).__name__}"
                )
            out[field.key] = [
                check_scalar(item, f"{where}/{i}") for i, item in enumerate(found)
            ]
        elif isinstance(field, Group):
            resolve(document, path, origin)  # refuse early if the group is gone
            out[field.key] = project(document, field.fields, origin, path)
        elif isinstance(field, Rows):
            found = resolve(document, path, origin)
            if not isinstance(found, list):
                raise SourceContractError(
                    f"{where}: Rows needs a list, found {type(found).__name__}"
                )
            out[field.key] = [
                project(document, field.fields, origin, path + (index,))
                for index in range(len(found))
            ]
        elif isinstance(field, Keyed):
            found = resolve(document, path, origin)
            if not isinstance(found, dict):
                raise SourceContractError(
                    f"{where}: Keyed needs an object, found {type(found).__name__}"
                )
            rows = []
            for name in found:
                row = {field.name: name}
                row.update(project(document, field.fields, origin, path + (name,)))
                rows.append(row)
            out[field.key] = rows
        elif isinstance(field, Derived):
            values = [resolve(document, base + p, origin) for p in field.inputs]
            out[field.key] = check_scalar(field.compute(*values), where)
        else:  # pragma: no cover -- the vocabulary is closed
            raise SourceContractError(f"{where}: unknown field kind {field!r}")

        if len(out) != seen.index(field.key) + 1:  # pragma: no cover
            raise SourceContractError(
                f"{where}: {field.key} did not reach the output"
            )
    return out


# -- the derived values --------------------------------------------------------
#
# Six, and each one is arithmetic on figures the reports measured. They exist
# because the alternative is a number typed into the page's prose, which the bake
# cannot protect.


def f1(true_positives: float, predicted: float, truth: float) -> float:
    return 2.0 * true_positives / (predicted + truth)


def one_event_f1_delta(true_positives: int, predicted: int, truth: int) -> float:
    """How far one phantom event moves F1 at the engine's own operating point.

    The ground-truth set has 17 crossings, so a single added or removed event is
    a large fraction of every rate on this page. Printing F1 to more digits than
    this invites a precision the measurement does not have, and any two methods
    closer together than this differ by one event rather than in quality.
    """
    return abs(
        f1(true_positives, predicted, truth) - f1(true_positives, predicted - 1, truth)
    )


def one_event_precision_delta(truth: int) -> float:
    """The same resolution on precision: one event in a set of ``truth``."""
    return 1.0 / truth


def cpu_multiple(engine_ms: float, baseline_ms: float) -> float:
    """What the engine's Kalman filter and second association stage cost.

    Both figures are the tracker and the counting rule only, on cached
    detections, so this is the association cost and excludes the detector
    entirely -- which is by far the larger cost in a real session.
    """
    return engine_ms / baseline_ms


def scaled_stress(multiple: float, at_sigma: float, to_sigma: float) -> float:
    """A jitter stress multiple moved from one sigma to another.

    The sweep's knob is a per-corner sigma and the stress multiple is that sigma
    over the measured residual, so it is linear in sigma: the multiple at 2 px is
    the multiple at 8 px times 2/8.
    """
    return multiple * to_sigma / at_sigma


