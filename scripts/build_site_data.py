#!/usr/bin/env python3
"""Bake ``reports/*.json`` into ``web/src/generated/reports.ts``.

Every measured number the site prints comes from this file, so the page cannot
drift from what was measured. The pattern is the one
``scripts/export_constants.py`` established: a generator with a narrow,
declarative contract, a committed artefact, and a sync test that fails whichever
side moved -- see ``tests/test_site_data_sync.py``.

Why a projection rather than the whole of ``reports/``:

    The seven report files are about 700 kB of JSON and carry per-frame
    false-positive lists thousands of entries long. Shipping them whole would
    put a megabyte of benchmark internals into a page bundle. So this script
    publishes a DECLARED subset -- ``PUBLISHED`` below -- and every mechanism
    here exists to stop that subset becoming a quiet, unnoticed one:

      * every field names an explicit path into its source, and an unresolvable
        path refuses the whole export rather than emitting a hole;
      * every report file present in ``reports/`` must be declared, so a new
        benchmark cannot be silently left off the site;
      * duplicate keys within one group are refused, because the loser of the
        collision would vanish and the artefact would still regenerate
        byte-identically -- exactly the failure byte equality cannot see;
      * the six derived values name their inputs and their formula, and the sync
        test recomputes each one from the source JSON independently.

Two things are deliberately NOT published, and the generator refuses to run if
either becomes reachable:

    ``parity.realClip.maxSpeedKmh`` and the two speed counts beside it. They are
    absolute km/h derived from ``motorway-a40.webm``, whose along-road scale is
    bracketed at -33 %/+0 % because no independent along-road anchor exists in
    the footage -- see ``reports/speed_real.json``. A number with that bracket is
    not a speed, ``configs/motorway.yaml`` ships with no calibration block, and
    the engine returns ``None`` for speed on that clip by design. Publishing the
    figure anywhere on the page would re-assert a claim the project's own
    measurement withdrew, so the redaction is enforced here, at the boundary,
    rather than left to whoever writes the next section.

Usage:

    PYTHONPATH=src .venv/bin/python scripts/build_site_data.py

The reports are read as data and never executed, and the output is a pure
function of the inputs: no timestamp, no machine name, no directory listing
order. That is what lets `npm run build` reproduce `docs/` byte for byte.
"""

