# -- the model card ------------------------------------------------------------
#
# The int8 comparison is a measurement, and it lives in the model card's table
# rather than in reports/ because it was made about the browser export and ships
# beside it. Parsed rather than transcribed for the same reason everything else
# here is: a number typed onto the page is a number the bake cannot protect.

#: Each declared row: the card's own row label, the type of its cells, and the
#: columns that MUST carry a figure.
#:
#: The last element is the condition this second data source was accepted on. A
#: card with an em-dashed cell used to bake to ``null`` and exit 0, and the page
#: then printed that null into a published table -- so the parse has to refuse on
#: every declared cell, not only on the three the derived figures are computed
#: from. A silent fallback here turns "the card is a source because the parse
#: fails loudly" into a hole.
#:
#: ``recall against float32`` and ``mean IoU of matched boxes`` genuinely have no
#: float32 cell: they are measured AGAINST float32, so the reference has no value
#: of its own to state and the card writes an em dash. That is a declared shape,
#: which is why the required columns are named per row rather than assumed.
MODEL_CARD_ROWS = {
    "fileSizeBytes": ("File size", int, ("float32", "int8")),
    "detections": ("Detections over 40 frames", int, ("float32", "int8")),
    "recallAgainstFloat32": ("Recall against float32", float, ("int8",)),
    "meanIouOfMatched": ("Mean IoU of matched boxes", float, ("int8",)),
}

_NUMERAL = r"\d+(?:\.\d+)?"

MODEL_CARD_PROTOCOL = re.compile(
    rf"(?P<frames>\d+) frames sampled every (?P<stride>\d+)\w* from.*?"
    rf"confidence (?P<conf>{_NUMERAL}) and IoU (?P<iou>{_NUMERAL})",
    re.DOTALL,
)


#: A markdown footnote reference riding along in a table cell -- the card
#: carries one on the float32 file size, explaining a nine-byte difference
#: between two of its own tables. It is prose about the figure, not part of it.
_FOOTNOTE = re.compile(r"\[\^[^\]]+\]")


def _number(text: str, kind: type) -> object:
    """A figure out of a model-card cell, or a refusal.

    Spaces inside a numeral are the card's thousands separator (``10 667 814``),
    and an em dash marks a cell the comparison does not fill.
    """
    cleaned = _FOOTNOTE.sub("", text)
    for space in (" ", "\u00a0", "\u202f", "\u2009"):
        cleaned = cleaned.replace(space, "")
    cleaned = cleaned.replace(",", "").strip()
    cleaned = cleaned.removesuffix("B")
    if cleaned in {"—", "-", ""}:
        return None
    try:
        return kind(cleaned)
    except ValueError as error:
        raise SourceContractError(f"cannot read {text!r} as {kind.__name__}") from error


def read_model_card(text: str, origin: str) -> dict:
    """The int8-versus-float32 comparison, out of the card's own table.

    Anchored on the row labels rather than on row positions, and every declared
    row must be found: a card that is reworded refuses the export instead of
    publishing a table with a hole in it.
    """
    cells: dict[str, list[str]] = {}
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        parts = [part.strip() for part in line.strip().strip("|").split("|")]
        if len(parts) == 3:
            cells[parts[0]] = parts[1:]

    out: dict[str, object] = {}
    missing = []
    for key, (label, kind, _required) in MODEL_CARD_ROWS.items():
        if label not in cells:
            missing.append(label)
            continue
        float32, int8 = cells[label]
        out[key] = {
            "float32": _number(float32, kind),
            "int8": _number(int8, kind),
        }
    if missing:
        raise SourceContractError(
            f"{origin}: the int8 comparison table has no row labelled "
            f"{missing}; the export cannot publish a figure it cannot find"
        )

    # Every declared cell, not only the ones arithmetic reads. An emptied cell
    # used to bake to `null` and exit 0, and the architecture table then printed
    # it -- a hole in a published comparison, arriving through the source that was
    # accepted precisely because it would refuse loudly.
    empty = [
        f"{label} / {column}"
        for key, (label, _kind, required) in MODEL_CARD_ROWS.items()
        for column in required
        if cast(dict, out[key])[column] is None
    ]
    if empty:
        raise SourceContractError(
            f"{origin}: the int8 comparison table leaves {empty} empty, and the "
            f"page publishes every declared cell of it; a figure the card does "
            f"not carry is not a figure the site may print"
        )

    protocol = MODEL_CARD_PROTOCOL.search(text)
    if protocol is None:
        raise SourceContractError(
            f"{origin}: the int8 comparison states no protocol (frames sampled, "
            f"confidence, NMS IoU); a figure without one does not ship"
        )

    # The three cells the two derived figures below are computed from are a subset
    # of the required cells checked above, so by here they are known present. The
    # narrowing is for the type checker and for the arithmetic that follows.
    size = out["fileSizeBytes"]
    recall = out["recallAgainstFloat32"]
    assert isinstance(size, dict) and isinstance(recall, dict)

    return {
        "source": "web/public/models/MODEL_CARD.md",
        "sampledFrames": int(protocol.group("frames")),
        "sampleStride": int(protocol.group("stride")),
        "confidence": float(protocol.group("conf")),
        "nmsIou": float(protocol.group("iou")),
        **out,
        # Derived, and stated as such: the two headline figures of the refusal.
        # bytesSaved is the difference of the two measured sizes;
        # detectionsLostFraction is one minus the measured recall.
        "bytesSaved": size["float32"] - size["int8"],
        "detectionsLostFraction": 1.0 - recall["int8"],
    }


# -- enforcing the redactions --------------------------------------------------

#: A step that stands for "every index of this list" or "every key of this
#: object" -- what Rows and Keyed expand over. Path comparison has to treat one
#: as matching anything, or a redaction inside a row would look unreachable.
WILDCARD = "*"


def declared_paths(fields: tuple, base: Path_ = ()):
    """Every source path the spec reads, with Rows/Keyed expansions wildcarded."""
    for field in fields:
        if isinstance(field, Derived):
            for path in field.inputs:
                yield base + path
            continue
        path = base + field.path
        if isinstance(field, (Value, Series)):
            yield path
        elif isinstance(field, Group):
            yield from declared_paths(field.fields, path)
        elif isinstance(field, (Rows, Keyed)):
            yield from declared_paths(field.fields, path + (WILDCARD,))
        else:  # pragma: no cover -- the vocabulary is closed
            raise SourceContractError(f"unknown field kind {field!r}")


def paths_overlap(declared: Path_, redacted: Path_) -> bool:
    """Whether one path could reach the other's value.

    True when either is a prefix of the other under wildcard matching: a field
    declared at ``realClip`` publishes everything beneath it, and a field
    declared at ``realClip/maxSpeedKmh`` publishes the redacted value itself.
    """
    for mine, theirs in zip(declared, redacted):
        if mine == WILDCARD or theirs == WILDCARD:
            continue
        if mine != theirs:
            return False
    return True


def keys_in(value: object, out: set | None = None) -> set:
    out = set() if out is None else out
    if isinstance(value, dict):
        for key, item in value.items():
            out.add(key)
            keys_in(item, out)
    elif isinstance(value, list):
        for item in value:
            keys_in(item, out)
    return out


#: Below this many characters a JSON literal is too common to search for -- a
#: small integer like `473` occurs all over a report as a frame index or a
#: detection count, and a substring guard on it would refuse every honest bake.
#: The structural check below is what protects those; the textual one is a second
#: line of defence for the distinctive figures, which is where it earns its keep.
DISTINCTIVE_LITERAL = 8


def enforce_redactions(
    reports: dict[str, object], baked: dict[str, object], body: str
) -> None:
    """Three checks, because one is not enough.

    Structural: no declared field may reach a redacted path. This is the one that
    actually holds -- it reasons about the spec rather than about the output text.

    By name: the redacted leaf name must not appear as a key anywhere in the
    output, so a later field cannot arrive at the same figure under the same name
    by another route.

    Textual: a distinctive literal must not appear in the rendered file at all.
    Belt and braces, and the reason the prohibition is worth enforcing here: this
    one figure must not reach the page by any path, including one nobody
    anticipated when writing the spec.

    Every redaction must also still RESOLVE in its source. A redaction for a key
    that has gone is a stale rule, and leaving it in place would quietly stop
    protecting anything.
    """
    output_keys = keys_in(baked)
    for redaction in REDACTED:
        source = reports.get(redaction.file)
        if source is None:
            raise SourceContractError(
                f"{redaction.file} is redacted from but is not in reports/"
            )
        value = resolve(source, redaction.path, redaction.file)
        check_scalar(value, f"{redaction.file}:{pointer(redaction.path)}")

        report = next(r for r in PUBLISHED if r.file == redaction.file)
        for declared in declared_paths(report.fields):
            if paths_overlap(declared, redaction.path):
                raise SourceContractError(
                    f"{redaction.file}: the spec reads {pointer(declared)}, which "
                    f"reaches the redacted {pointer(redaction.path)}. It is "
                    f"redacted because {redaction.reason}."
                )

        leaf = str(redaction.path[-1])
        if leaf in output_keys:
            raise SourceContractError(
                f"{redaction.file}: the output carries a key named {leaf!r}, which "
                f"is the redacted {pointer(redaction.path)}. It is redacted "
                f"because {redaction.reason}."
            )

        literal = json.dumps(value)
        if len(literal) >= DISTINCTIVE_LITERAL and literal in body:
            raise SourceContractError(
                f"{redaction.file}:{pointer(redaction.path)} reached the output as "
                f"{literal}. It is redacted because {redaction.reason}."
            )


# -- rendering -----------------------------------------------------------------


def render(reports: dict[str, object], model_card: str) -> str:
    """The whole TypeScript file, as a pure function of its inputs."""
    declared = {report.file for report in PUBLISHED}
    present = set(reports)
    if declared != present:
        undeclared = sorted(present - declared)
        absent = sorted(declared - present)
        raise SourceContractError(
            "reports/ and the PUBLISHED spec disagree. "
            + (f"Not declared: {undeclared}. " if undeclared else "")
            + (f"Declared but missing: {absent}. " if absent else "")
            + "A benchmark that is not declared would never reach the site, and "
            "the artefact would still regenerate byte-identically."
        )

    baked: dict[str, object] = {}
    for report in PUBLISHED:
        document = reports[report.file]
        section = project(document, report.fields, report.file)
        section["source"] = f"reports/{report.file}"
        baked[report.key] = section

    baked["model"] = read_model_card(model_card, "MODEL_CARD.md")

    body = json.dumps(baked, indent=2, ensure_ascii=False, allow_nan=False)
    enforce_redactions(reports, baked, body)

    lines = [
        HEADER.rstrip("\n"),
        "",
        "/** Every measured figure the results sections print, baked from the",
        " * reports named in each section's `source` field. Read from here and",
        " * never retyped: a figure typed into markup is one the bake cannot",
        " * keep in step with the measurement. */",
        f"export const REPORTS = {body} as const;",
        "",
        "export type Reports = typeof REPORTS;",
    ]
    return "\n".join(lines) + "\n"


def read_reports(directory: Path) -> dict[str, object]:
    """Every ``*.json`` directly inside ``directory``, keyed by file name.

    Sorted, so the read order is a property of the names rather than of the
    filesystem -- the output has to be reproducible on another machine.
    """
    if not directory.is_dir():
        raise SourceContractError(f"{directory} is not a directory")
    found = {}
    for path in sorted(directory.glob("*.json")):
        try:
            found[path.name] = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise SourceContractError(f"{path.name}: {error}") from error
    if not found:
        raise SourceContractError(f"{directory} holds no report files")
    return found


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate web/src/generated/reports.ts from reports/*.json."
    )
    parser.add_argument("--reports", default=str(DEFAULT_REPORTS))
    parser.add_argument("--model-card", default=str(DEFAULT_MODEL_CARD))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    out_path = Path(args.out)

    try:
        reports = read_reports(Path(args.reports))
        model_card = Path(args.model_card).read_text(encoding="utf-8")
        rendered = render(reports, model_card)
    except (SourceContractError, OSError) as error:
        print(
            f"refusing to bake the site data: every figure the page prints must "
            f"resolve to a value in reports/ or the model card, and nothing "
            f"redacted may reach the output.\n\n{error}",
            file=sys.stderr,
        )
        return 1

    out_path.parent.mkdir(parents=True, exist_ok=True)
    # newline="" so the "\n" endings survive on every platform: byte equality
    # with a fresh bake is the contract and the default would translate them.
    with open(out_path, "w", encoding="utf-8", newline="") as handle:
        handle.write(rendered)

    print(f"wrote {out_path} ({len(rendered.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
